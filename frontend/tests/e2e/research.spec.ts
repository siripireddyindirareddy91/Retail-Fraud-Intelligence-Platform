import { test, expect } from '@playwright/test';
import { signIn } from './support';
test('complete research workflow uses real generators, detectors, explanations, evaluation and PDF export',async({page},info)=>{
 test.setTimeout(600000);
 await signIn(page);
 const completed=async()=>{await expect(page.getByRole('heading',{name:'Job · succeeded',exact:true})).toBeVisible({timeout:180000});await expect(page.locator('.result-view')).toBeVisible();};
 await page.goto('/synthetic/generate');
 await page.getByLabel('Dataset name',{exact:true}).fill('Research baseline');
 await page.getByLabel('Transactions',{exact:true}).fill('1000');
 await page.getByLabel('Fraud percentage',{exact:true}).fill('12');
 await page.getByRole('button',{name:'Generate dataset',exact:true}).click();
 await completed();
 await expect(page.getByLabel('Dataset',{exact:true})).not.toHaveValue('');
 const dataset=await page.getByLabel('Dataset',{exact:true}).inputValue();
 expect(dataset).toBeTruthy();
 await expect(page.getByRole('columnheader',{name:'transaction amount',exact:true})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0)); await page.screenshot({path:`test-results/research-generation-${info.project.name}.png`,fullPage:true});
 await page.goto('/models/train');
 await page.getByLabel('Dataset',{exact:true}).selectOption(dataset);
 await page.getByLabel('Algorithm',{exact:true}).selectOption('Logistic Regression');
 await page.getByLabel('Model name',{exact:true}).fill('Research logistic regression');
 await page.getByRole('button',{name:'Train model',exact:true}).click();
 await completed();
 await expect(page.getByText('Confusion matrix',{exact:true})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0)); await page.screenshot({path:`test-results/research-model-${info.project.name}.png`,fullPage:true});
 await page.goto('/fraud/detect');
 await page.getByLabel('Dataset',{exact:true}).selectOption(dataset);
 await page.getByRole('button',{name:'Score transactions',exact:true}).click();
 await completed();
 await expect(page.getByRole('columnheader',{name:'ground truth',exact:true})).toBeVisible();
 await page.goto('/explainability/shap');
 await page.getByLabel('Dataset',{exact:true}).selectOption(dataset);
 await page.getByLabel('Explanation samples',{exact:true}).fill('3');
 await page.getByRole('button',{name:'Calculate SHAP values',exact:true}).click();
 await completed();
 await expect(page.getByText('SHAP summary · individual feature contributions',{exact:true})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0)); await page.screenshot({path:`test-results/research-shap-${info.project.name}.png`,fullPage:true});
 await page.goto('/robustness');
 await page.getByLabel('Dataset',{exact:true}).selectOption(dataset);
 await page.getByLabel('Detector',{exact:true}).selectOption('Logistic Regression');
 await page.getByLabel('Repeated seeds',{exact:true}).fill('42');
 await page.getByRole('button',{name:'Run robustness study',exact:true}).click();
 await completed();
 await expect(page.getByText('Shared-test baseline versus augmented recall',{exact:true})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0)); await page.screenshot({path:`test-results/research-robustness-${info.project.name}.png`,fullPage:true});
 await page.goto('/synthetic/models');
 await page.getByLabel('Dataset',{exact:true}).selectOption(dataset);
 await page.getByLabel('Epochs',{exact:true}).fill('1');
 await page.getByRole('button',{name:'Train synthesizer',exact:true}).click();
 await completed();
 await page.goto('/synthetic/generate');
 await page.getByLabel('Generation method',{exact:true}).selectOption('CTGAN');
 await page.getByLabel('Dataset name',{exact:true}).fill('Conditional learned transactions');
 await page.getByLabel('Transactions',{exact:true}).fill('100');
 await page.getByLabel('Fraud percentage',{exact:true}).fill('10');
 await page.getByLabel('Conditions',{exact:true}).fill('{"payment_method":"card"}');
 await page.getByRole('button',{name:'Generate dataset',exact:true}).click();
 await completed();
 await expect(page.getByRole('columnheader',{name:'transaction amount',exact:true})).toBeVisible();
 await page.goto('/reports');
 const choice=page.getByLabel('Research run',{exact:true}).locator('option').filter({hasText:'model.train'}).first();
 await expect(choice).toBeAttached();
 await page.getByLabel('Research run',{exact:true}).selectOption((await choice.getAttribute('value'))!);
 await page.getByRole('button',{name:'Generate report',exact:true}).click();
 await completed();
 const ready=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download artifact',exact:true}).click();
 expect((await ready).suggestedFilename()).toMatch(/\.pdf$/);
 await page.goto('/dashboard');
 await expect(page.getByText('1,100',{exact:true})).toBeVisible();
 await expect(page.getByText('Model held-out performance',{exact:true})).toBeVisible(); await expect(page.locator('.recharts-pie-sector').first()).toBeAttached();
 await page.evaluate(()=>window.scrollTo(0,0)); await page.screenshot({path:`test-results/research-dashboard-${info.project.name}.png`,fullPage:true});
 expect(await page.locator('body').evaluate(element=>element.scrollWidth<=element.clientWidth)).toBe(true);
});

