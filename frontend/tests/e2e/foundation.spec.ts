import { test, expect } from '@playwright/test';
import { signIn } from './support';

test('authenticated foundation persists settings and experiments, runs a real worker job and logs out',async({page})=>{
 const account=await signIn(page);
 await page.reload();
 await expect(page.getByRole('heading',{level:1})).toContainText('Intelligence starts');
 expect(await page.evaluate(()=>Object.keys(localStorage).some(key=>/token|password/i.test(key)))).toBe(false);
 await page.goto('/settings');
 await page.getByLabel('Display name').fill('Persisted Researcher');
 await page.getByLabel('Color theme').selectOption('dark');
 await page.getByRole('button',{name:'Save account preferences'}).click();
 await expect(page.getByRole('status')).toContainText('saved to your account');
 await page.reload();
 await expect(page.getByLabel('Display name')).toHaveValue('Persisted Researcher');
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.goto('/experiments');
 const name=`Paired study ${Date.now()}`;
 await page.getByLabel('Experiment name').fill(name);
 await page.getByRole('button',{name:'Create experiment draft'}).click();
 await expect(page.getByRole('cell',{name,exact:true})).toBeVisible();
 await page.goto('/experiments/history');
 await expect(page.getByRole('cell',{name,exact:true})).toBeVisible();
 await page.goto('/system/health');
 await expect(page.getByRole('row').filter({has:page.getByRole('cell',{name:'worker',exact:true})})).toContainText('available');
 await page.getByRole('button',{name:'Run integrity check'}).click();
 await expect(page.getByRole('status')).toContainText('succeeded',{timeout:20000});
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download integrity report'}).click();
 const download=await downloadPromise;
 expect(download.suggestedFilename()).toBe('artifact-integrity-report.json');
 await page.getByRole('button',{name:'Workspace profile'}).click();
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await expect(page.getByRole('heading',{level:1,name:'Welcome back.'})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('heading',{level:1,name:'Welcome back.'})).toBeVisible();
 await page.getByLabel('Email',{exact:true}).fill(account.email);
 await page.getByLabel('Password',{exact:true}).fill(account.password);
 await page.locator('form').getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByRole('heading',{level:1,name:'System Health',exact:true})).toBeVisible();
 await expect(page).toHaveURL(/\/system\/health$/);
});
